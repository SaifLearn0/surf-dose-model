# Data-integrity summary: day-1 and day-14 numbers, urea loss, nitrogen gap.
UREA_MW = 60.06
N_FRACTION = (2 * 14.007) / UREA_MW   # urea-molecule mg/L -> urea-N mg/L

def integrity_summary():
    for key in ("CA", "WV"):
        d = DATA[key]; meta = d["meta"]
        print("\n" + meta["name"] + "  -- day1 -> day14 summary")
        print(f"{'Treatment':16s}{'pH d1->d14':>14s}{'urea loss%':>12s}"
              f"{'TAN d1->d14':>16s}{'N-gap%':>9s}")
        for j,(label,_,_,_,opt) in enumerate(meta["treatments"]):
            u1,u14 = d["UREA"][0,j], d["UREA"][-1,j]
            t1,t14 = d["TAN"][0,j],  d["TAN"][-1,j]
            p1,p14 = d["pH"][0,j],   d["pH"][-1,j]
            urea_loss = 100*(u1-u14)/u1
            totN1  = u1*N_FRACTION + t1
            totN14 = u14*N_FRACTION + t14
            ngap = 100*(totN1-totN14)/totN1
            star = "  <-- optimum" if opt else ""
            print(f"{label:16s}{p1:6.2f}->{p14:<5.2f}{urea_loss:11.1f}%"
                  f"{t1:6.0f}->{t14:<6.0f}{ngap:7.1f}%{star}")
    print("\nN-gap% = fraction of total N (urea-N + TAN) lost over 14 d.")
    print("It grows where pH climbed high -> consistent with NH3 volatilisation")
    print("through the open flasks (handled by the NH3-loss term in Step 3).")

# Plots: clean Origin-style (no grid, uniform lines, marker per series, frame on).
def plot_variable(key, var, ylabel, title):
    d = DATA[key]; meta = d["meta"]
    mean = d[var]; sd = d[var + "_sd"]
    plt.figure(figsize=(7,5))
    for j,(label,_,_,colour,opt) in enumerate(meta["treatments"]):
        lab = label + " (optimum)" if opt else label
        plt.errorbar(DAYS, mean[:,j], yerr=sd[:,j], label=lab, color=colour,
                     lw=1.3, marker=MARKERS[j], ms=4.5, markeredgewidth=0.5,
                     capsize=2, capthick=0.7, elinewidth=0.7, ecolor=to_rgba(colour, 0.4),
                     markeredgecolor=colour, markerfacecolor=colour)
    plt.xlabel("Days"); plt.ylabel(ylabel)
    plt.title(title)
    plt.xlim(0, 15)
    plt.legend(fontsize=9, frameon=False)
    plt.tight_layout()

def make_all_plots():
    for key in ("CA","WV"):
        name = DATA[key]["meta"]["name"]
        plot_variable(key, "UREA", "Urea (mg/L)",   "Urea  --  " + name)
        plot_variable(key, "pH",   "pH",            "pH  --  " + name)
        plot_variable(key, "TAN",  "TAN (mg/L)",    "TAN  --  " + name)
    plt.show()

if __name__ == "__main__":
    integrity_summary()
    make_all_plots()
